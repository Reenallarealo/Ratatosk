// ── Language enum ─────────────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq)]
pub enum Language { Zh, ZhTw, En, Fr, It, De, Es, Ja, Ko, Ru, PtBr, Pl, Tr }

impl Language {
    pub fn strings(&self) -> &'static Lang {
        match self {
            Language::Zh   => &ZH,
            Language::ZhTw => &ZH_TW,
            Language::En   => &EN,
            Language::Fr   => &FR,
            Language::It   => &IT,
            Language::De   => &DE,
            Language::Es   => &ES,
            Language::Ja   => &JA,
            Language::Ko   => &KO,
            Language::Ru   => &RU,
            Language::PtBr => &PT_BR,
            Language::Pl   => &PL,
            Language::Tr   => &TR,
        }
    }
    pub fn as_str(&self) -> &'static str {
        match self {
            Language::Zh   => "zh",
            Language::ZhTw => "zh-tw",
            Language::En   => "en",
            Language::Fr   => "fr",
            Language::It   => "it",
            Language::De   => "de",
            Language::Es   => "es",
            Language::Ja   => "ja",
            Language::Ko   => "ko",
            Language::Ru   => "ru",
            Language::PtBr => "pt-br",
            Language::Pl   => "pl",
            Language::Tr   => "tr",
        }
    }
    pub fn from_str(s: &str) -> Self {
        match s {
            "zh-tw" => Language::ZhTw,
            "en"    => Language::En,
            "fr"    => Language::Fr,
            "it"    => Language::It,
            "de"    => Language::De,
            "es"    => Language::Es,
            "ja"    => Language::Ja,
            "ko"    => Language::Ko,
            "ru"    => Language::Ru,
            "pt-br" => Language::PtBr,
            "pl"    => Language::Pl,
            "tr"    => Language::Tr,
            _       => Language::Zh,
        }
    }
    pub fn label(&self) -> &'static str {
        match self {
            Language::Zh   => "简体中文",
            Language::ZhTw => "繁體中文",
            Language::En   => "English",
            Language::Fr   => "Français",
            Language::It   => "Italiano",
            Language::De   => "Deutsch",
            Language::Es   => "Español",
            Language::Ja   => "日本語",
            Language::Ko   => "한국어",
            Language::Ru   => "Русский",
            Language::PtBr => "Português (BR)",
            Language::Pl   => "Polski",
            Language::Tr   => "Türkçe",
        }
    }
}
